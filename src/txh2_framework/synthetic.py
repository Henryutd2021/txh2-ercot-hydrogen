"""A small synthetic study region for examples and tests.

SYNTHETIC DATA. Nothing here is ERCOT data or the data of the article: the zones, profiles,
capacities, distances and parameter values are invented, round and illustrative, chosen only so
that the example exercises every part of the model (surplus renewable hours, zones with and
without hydrogen demand, pipeline transport, storage). Results obtained with them say nothing
about Texas.

The scenario tree uses the structure of the article's Tables 1-2 (three demand levels, three
completion levels of planned renewable capacity); see ``docs/scenarios.md``.
"""

from __future__ import annotations

import numpy as np

from .inputs import BaseInputs, Pipeline
from .parameters import Parameters
from .scenarios import Level, ScenarioTree

SYNTHETIC_NOTICE = (
    "SYNTHETIC DATA generated by txh2_framework.synthetic. Not ERCOT data and not the data of the "
    "article; all values are illustrative."
)


def illustrative_parameters() -> Parameters:
    """Round, illustrative techno-economic values (k$, MWh, t). Not calibrated to any study."""
    return Parameters(
        c_ins={"electrolyzer": 1000.0, "tank": 500.0, "fuel_cell": 1500.0},   # k$/MW, k$/t, k$/MW
        c_om={"electrolyzer": 30.0, "tank": 10.0, "fuel_cell": 40.0},         # per year
        delta=0.05,
        lifetime=25,
        lambda_e2h=55.0,     # MWh per t of hydrogen produced
        lambda_h2e=16.0,     # MWh generated per t of hydrogen
        eta_cha=0.92,
        eta_dis=0.92,
        rho_h=3.0,           # k$/t
        rho_o=0.01,          # k$/t
        c_w=0.002,           # k$/t of water
        r_w=9.0,             # t of water per t of hydrogen (stoichiometric)
        r_o=8.0,             # t of oxygen per t of hydrogen (stoichiometric)
        c_tr=0.002,          # k$ per t and km
        c_s=0.05,            # k$ per t CO2
        f_smr=9.0,           # t CO2 per t hydrogen
        h_cost=1.5,          # k$ per t
        c_p=0.06,            # k$ per t CO2
        f_power=0.4,         # t CO2 per MWh
        c_pen=0.06,          # k$ per MWh
    )


def article_scenario_tree() -> ScenarioTree:
    """The scenario design of the article's Table 1: demand -2 % / projection / +2 % with
    probabilities 0.2 / 0.5 / 0.3; completion of planned renewables 0 % / 30 % / 80 % with
    probabilities 0.1 / 0.7 / 0.2."""
    return ScenarioTree(
        demand_levels=(Level("L", 0.98, 0.2), Level("M", 1.00, 0.5), Level("H", 1.02, 0.3)),
        completion_levels=(Level("L", 0.0, 0.1), Level("M", 0.3, 0.7), Level("H", 0.8, 0.2)),
    )


def _wind(rng, hours, mean, phase):
    t = np.arange(hours)
    daily = 0.15 * np.cos(2 * np.pi * (t - phase) / 24)          # stronger at night
    slow = 0.25 * np.sin(2 * np.pi * t / (hours / 1.5) + phase)    # multi-day weather swing
    noise = np.convolve(rng.normal(0, 0.12, hours + 5), np.ones(6) / 6, mode="valid")[:hours]
    return np.clip(mean + daily + slow + noise, 0.02, 0.95)


def _solar(hours, peak):
    t = np.arange(hours) % 24
    shape = np.clip(np.sin(np.pi * (t - 6) / 12), 0, None)       # daylight 06:00-18:00
    return peak * shape


def synthetic_inputs(zones: int = 4, hours: int = 72, seed: int = 7) -> BaseInputs:
    """A small region: ``zones`` zones on a ring (each adjacent to its two neighbours), ``hours``
    hourly steps. Zone Z1 is wind-rich with little demand; the last zone is a demand centre with
    most of the hydrogen demand; the others are in between."""
    if zones < 2:
        raise ValueError("need at least two zones")
    rng = np.random.default_rng(seed)
    names = tuple(f"Z{n + 1}" for n in range(zones))
    t = np.arange(hours) % 24
    load_shape = 1 + 0.18 * np.sin(2 * np.pi * (t - 9) / 24)         # afternoon peak

    base_load = np.linspace(80, 400, zones)                           # MW
    wind_cap = np.linspace(400, 60, zones)                            # MW of existing wind
    solar_cap = np.linspace(60, 160, zones)                           # MW of existing solar
    planned_wind = np.linspace(300, 40, zones)                        # MW planned by the target year
    planned_solar = np.linspace(120, 200, zones)

    demand = np.empty((zones, hours))
    existing = np.empty((zones, hours))
    planned = np.empty((zones, hours))
    for i in range(zones):
        cf_w = _wind(rng, hours, mean=0.42 - 0.04 * i, phase=3 * i)
        cf_s = _solar(hours, peak=0.85)
        demand[i] = base_load[i] * load_shape * (1 + rng.normal(0, 0.02, hours))
        existing[i] = wind_cap[i] * cf_w + solar_cap[i] * cf_s
        planned[i] = planned_wind[i] * cf_w + planned_solar[i] * cf_s   # same capacity factors as the zone's fleet

    h2_rate = np.zeros(zones)                                         # t per hour
    h2_rate[-1] = 4.0
    if zones > 2:
        h2_rate[zones // 2] = 1.5
    h2_demand = np.repeat(h2_rate[:, None], hours, axis=1)

    pipelines = [Pipeline(names[i], names[(i + 1) % zones], float(rng.integers(150, 450)))
                 for i in range(zones if zones > 2 else 1)]
    return BaseInputs(
        zones=names,
        demand=np.round(demand, 3),
        renewable_existing=np.round(existing, 3),
        renewable_planned=np.round(planned, 3),
        h2_demand=h2_demand,
        battery_existing=np.linspace(40, 120, zones),
        battery_planned=np.linspace(20, 60, zones),
        pipelines=tuple(pipelines),
        params=illustrative_parameters(),
        description=SYNTHETIC_NOTICE + f" zones={zones}, hours={hours}, seed={seed}.",
    )
